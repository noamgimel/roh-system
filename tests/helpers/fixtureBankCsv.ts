/** קידוד מחרוזת ל-windows-1255: ASCII כמו-שהוא, א-ת → 0xE0-0xFA. */
export function encodeCp1255(text: string): Buffer {
  const bytes: number[] = [];
  for (const ch of text) {
    const code = ch.codePointAt(0)!;
    if (code < 0x80) bytes.push(code);
    else if (code >= 0x05d0 && code <= 0x05ea) bytes.push(code - 0x05d0 + 0xe0);
    else throw new Error(`תו שאינו ניתן לקידוד ב-cp1255 בפיקסטורה: ${ch}`);
  }
  return Buffer.from(bytes);
}

